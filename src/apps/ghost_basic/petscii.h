// Map a PETSCII/ASCII code to a screen code (0..63). Lowercase folds to
// uppercase, matching the C64's default uppercase/graphics character set.
// Anything unprintable becomes a space.
constexpr uint8_t toScreenCode(uint8_t c) {
    if (c >= 32 && c <= 63)      return c;                 // space..? and digits
    if (c >= 64 && c <= 95)      return uint8_t(c - 64);   // @, A..Z, brackets
    if (c >= 'a' && c <= 'z')    return uint8_t(c - 96);   // see note below
    // The graphics half, reachable with CHR$(160..255).
    if (c >= 160 && c <= 191)    return uint8_t(c - 64);   // -> 96..127
    if (c >= 192 && c <= 223)    return uint8_t(c - 128);  // -> 64..95
    if (c >= 224 && c <= 254)    return uint8_t(c - 128);  // -> 96..126
    if (c == 255)                return 94;                // pi
    return 32;                                             // space
}
// Deviation from the original, on purpose: a real C64 reads 97..122 as the
// Shift+A..Z graphics, because its keyboard speaks PETSCII. Ours speaks ASCII,
// where those codes are lowercase letters — folding them to A..Z is what a
// typist expects. The graphics are all still reachable through CHR$(160..255).

