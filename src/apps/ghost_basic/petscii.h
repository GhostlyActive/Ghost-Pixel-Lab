// Map a PETSCII/ASCII code to a screen code (0..63). Lowercase folds to
// uppercase, matching the C64's default uppercase/graphics character set.
// Anything unprintable becomes a space.
constexpr uint8_t toScreenCode(uint8_t c) {
    if (c == '@')                return 0;
    if (c >= 'A' && c <= 'Z')    return uint8_t(c - 64);   // 1..26
    if (c >= 'a' && c <= 'z')    return uint8_t(c - 96);   // fold to A..Z
    if (c == '[')                return 27;
    if (c == 0x5C || c == 0x5F)  return 28;                // '\' / GBP slot
    if (c == ']')                return 29;
    if (c == '^')                return 30;
    if (c >= 32 && c <= 63)      return c;                 // space..? and digits
    return 32;                                             // space
}

